"""TC 설계 입력의 확인 항목 수를 집계합니다."""
# CHANGELOG · 2026-10-12: 공통 셸에서 TC 확인 항목 집계를 옮깁니다.


def check_items(tcs):
    """확인 항목 수 — 시트의 한 행이 확인 항목 하나입니다.

    케이스(TC ID) 수와 다릅니다. 한 케이스가 확인 항목을 여럿 갖기 때문입니다.
    시트·추적 매트릭스·자동화 리포트가 같은 계산을 쓰도록 이곳에서 집계합니다.
    각 TC의 여섯 번째 값은 단계별 기대결과 목록이며, 빈 단계도 한 행으로 셉니다.
    """
    return sum(sum(max(1, len(e)) for e in t[5]) for t in tcs)
